    /** super 只由超级角色标记授予；角色字符串不能授予身份、父节点或旧业务码。 */
    public static Set<String> fromRole(String role) {
        Set<String> result = new LinkedHashSet<>();
        if (role == null || role.isBlank()) return result;
        for (String raw : role.split(",")) {
            String code = raw.trim();
            if (!code.matches("[1-9][0-9]{0,8}")) continue;
            if (GRANTABLE_IDS.contains(Integer.parseInt(code))) result.add(code);
        }
        return result;
    }
